import Foundation

/// A 5 x 7 font, drawn by hand on the same grid as the cat.
///
/// A real typeface shrunk to nine pixels and rendered without antialiasing is
/// a squashed typeface, not a drawn one: the stems land where they land and
/// the letters come out uneven next to art that was placed pixel by pixel.
enum PixelFont {

    static let width = 5
    static let height = 7
    /// One blank column between letters.
    static let advance = 6

    static func glyph(_ character: Character) -> [String] {
        table[Character(character.uppercased())] ?? blank
    }

    static func has(_ character: Character) -> Bool {
        table[Character(character.uppercased())] != nil
    }

    private static let blank = Array(repeating: ".....", count: height)

    /// Everything the lines and the scramble can use, and nothing else.
    static let alphabet = Array("ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789#%*+-=/<>:.")

